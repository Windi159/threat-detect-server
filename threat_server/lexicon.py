"""욕설·위협 판정에 쓰는 규칙 사전.

입력은 Whisper가 받아쓴 **말**이다. 타이핑과 달리 `ㅅㅂ` 같은 자음 축약은 거의 나오지 않고,
대신 띄어쓰기와 문장부호가 들쭉날쭉하고 발음이 비슷한 변형(씨발/씨팔/쉬발)이 섞여 나온다.
그래서 전처리는 공백·부호 제거와 반복 글자 축약에 집중하고, 판정은 정규식으로 한다.

단순 부분문자열 매칭을 쓰지 않는 이유는 오탐 때문이다. `칼로`는 "칼로리"에, `새끼`는
"새끼손가락"과 "고양이 새끼"에, `꺼져`는 "불 꺼져 있나"에 걸린다. 규칙마다 전후 문맥을
배제 조건(lookaround)으로 적어 이런 경우를 걸러낸다.

가중치는 "이 표현만으로 관제 알람을 보낼 만한가"를 기준으로 매긴다.
  0.9~0.95  표현 자체가 명백한 위해 예고·욕설
  0.75~0.85 문맥상 대부분 공격적이지만 예외가 있는 표현
  0.5~0.65  단독으로는 애매한 표현 (기본 임계값 0.7 미만이라 알람은 안 가고 로그만 남는다)
"""

import re

LABELS = ("normal", "abuse", "threat")

# 공백·문장부호는 지운다. Whisper가 "죽여 버린다", "죽여버린다."처럼 제각각 내놓기 때문이다.
_PUNCT = re.compile(r"""[\s.,!?~…·\-_'"()\[\]{}<>:;/\\|@#$%^&*+=·ㆍ]+""")
# 한글 사이에 낀 숫자는 치환 문자로 본다 (시1발 → 시발)
_DIGIT_IN_HANGUL = re.compile(r"(?<=[가-힣])\d+(?=[가-힣])")
# 같은 글자 3번 이상 반복은 한 번으로 (죽어어어 → 죽어)
_REPEAT = re.compile(r"(.)\1{2,}")


def normalize(text: str) -> str:
    """판정용으로 문장을 압축한다. 사람이 읽을 용도가 아니다."""
    t = _PUNCT.sub("", text.strip().lower())
    t = _DIGIT_IN_HANGUL.sub("", t)
    return _REPEAT.sub(r"\1", t)


# --- 위협 ---------------------------------------------------------------------
# (이름, 정규식, 가중치)
THREAT_RULES: tuple[tuple[str, str, float], ...] = (
    # 살해 예고. "죽여주네"(칭찬), "시간 죽이기"는 배제한다.
    ("살해", r"(?<!시간)죽(여버|여놓|일거|일꺼|인다|여드|여줄게)", 0.95),
    ("살해", r"죽여(?!주|줍|줘요|준다|드려)", 0.9),
    ("살해", r"(죽어|뒤져)(라|버려|야지)(?!보|서)", 0.85),
    ("살해", r"(목졸|목을졸|숨통|매장시|파묻어)", 0.9),
    # 흉기. "칼로리", "칼국수"를 배제하려고 뒤에 오는 동사를 함께 요구한다.
    ("흉기", r"칼(로|을|들고)?(찌르|찔러|쑤시|휘두|그어)", 0.95),
    ("흉기", r"(찔러버|찔러죽|쑤셔버)", 0.95),
    # 흉기를 들고 온다는 말 자체가 위협이다. 뒤에 동사가 안 붙어도 잡는다.
    ("흉기", r"(칼|흉기|망치|쇠파이프|야구방망이|각목)(을|를)?(들고|가지고|챙겨|꺼내)", 0.9),
    ("흉기", r"(불질러|불태워|불지른다|염산|산성액)", 0.9),
    # 폭행. "때려치우다", "못을 때려 박다"는 때리는 대상이 사람이 아니다.
    ("폭행", r"때려(죽|부수|눕히|패)", 0.95),
    ("폭행", r"(패버리|패줄|패준다|두들겨패|후려갈|조져버리|밟아버리|작살내|박살내)", 0.9),
    ("폭행", r"(쳐버린다|갈겨버|턱을날)", 0.85),
    ("폭행", r"때릴(거|꺼|테|겁)", 0.85),
    # 보복 예고
    ("보복", r"가만(안둬|안둔|두지않|안둘|놔두지않|못있)", 0.85),
    ("보복", r"(각오해|각오하는|후회하게해|대가를치르|끝장내|손봐주|피보게)", 0.8),
    ("보복", r"(두고보자|두고봐라)", 0.65),
    # 신상·가족 협박 (스토킹성)
    # 압축해도 "가족들다알아낼거야"처럼 사이에 조사·부사가 끼므로 약간의 간격을 허용한다.
    ("신상협박", r"(신상|집주소|회사로|가족|애들|자식).{0,6}(털어|털어서|알아내|알아낼|찾아내|찾아낼)", 0.9),
    ("신상협박", r"(집앞|집까지|회사앞)(으로)?(찾아|가겠|간다|갈게)", 0.85),
    ("신상협박", r"찾아(간다|갈거|갈꺼|가겠)", 0.6),
)

# --- 욕설 ---------------------------------------------------------------------
ABUSE_RULES: tuple[tuple[str, str, float], ...] = (
    ("성적비하", r"(씨발|시발|씨팔|시팔|쉬발|씌발|쒸발|시벌|씨벌|스발)", 0.95),
    ("성적비하", r"(좆|좇같|존나|쥰내|지랄|염병|니미|니애미|엠창|애미)", 0.9),
    # 새끼: "고양이 새끼"(동물), "새끼손가락"(신체)은 욕이 아니다.
    ("인신공격", r"(?<!고양이)(?<!강아지)(?<!제비)새끼(?!손|발)", 0.85),
    ("인신공격", r"(개새|개세끼|개자식|호로|잡놈|잡년)", 0.95),
    ("인신공격", r"(병신|븅신|빙신|등신|머저리|쓰레기같|한심한놈)", 0.9),
    ("인신공격", r"미친(놈|년|새|것|거야|듯이행동)", 0.85),
    # 꺼져: "불 꺼져 있나", "화면 꺼져서"는 전원 이야기다.
    ("모욕", r"(?<!불)(?<!전원)(?<!화면)(?<!티비)(?<!시동)(?<!에어컨)꺼져(?!있|서|도|가|면)", 0.8),
    ("모욕", r"(닥쳐|닥치고|주둥이|아가리|싸가지없|싹수없|엿먹어|뒈져)", 0.85),
    ("모욕", r"(꼴값|주제에|어디서감히|배워먹)", 0.6),
    # 자음 축약. Whisper 전사문에는 거의 안 나오지만, 앱이 아닌 곳에서 타이핑으로 들어올 때를
    # 대비해 둔다. 낱자(ㅅㅂ)는 음절(시발)과 코드포인트가 달라 한글 단어 안에 걸릴 일이 없다.
    ("자음축약", r"(ㅅㅂ|ㅆㅂ|ㅄ|ㅂㅅ|ㄱㅅㄲ|ㅈㄹ|ㅁㅊ|ㅗ)", 0.8),
)

_COMPILED: dict[str, tuple[tuple[str, re.Pattern[str], float], ...]] = {
    "threat": tuple((n, re.compile(p), w) for n, p, w in THREAT_RULES),
    "abuse": tuple((n, re.compile(p), w) for n, p, w in ABUSE_RULES),
}


def matches(text: str) -> dict[str, list[tuple[str, float]]]:
    """라벨별로 걸린 규칙 목록을 돌려준다. 사전을 손볼 때 무엇이 걸렸는지 보기 위한 함수다."""
    compact = normalize(text)
    return {
        label: [(name, weight) for name, pattern, weight in rules if pattern.search(compact)]
        for label, rules in _COMPILED.items()
    }


def score(text: str) -> tuple[str, float]:
    """(라벨, 확신도)를 돌려준다.

    위협과 욕설이 함께 걸리면 위협을 택한다. 위협 알람이 더 급하고, 위협 문장에는 욕설이
    섞여 있는 경우가 많기 때문이다. 서로 다른 규칙이 여러 개 걸리면 확신도를 조금 올린다.
    """
    found = matches(text)
    for label in ("threat", "abuse"):
        hits = found[label]
        if not hits:
            continue
        top = max(w for _, w in hits)
        distinct = len({name for name, _ in hits})
        return label, min(0.99, top + 0.03 * (distinct - 1))
    return "normal", 1.0
